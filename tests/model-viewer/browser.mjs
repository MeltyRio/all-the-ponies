    assert.equal((await snapshot(runtime)).cachedAnimations, 0)
    passed.push('idempotent disposal releases WebGL context, DOM canvas and clip cache')

    // Delay a genuine request, then reset. The late response must not start a clip.
    await runtime.goto(`${server.url}/?runtime`)
    await runtime.waitForFunction(() => window.viewerTest?.controller.snapshot().ready)
    await runtime.evaluate(async () => {
        const clip = window.viewerTest.model.animations[0]
        const original = clip.rigKey
        clip.rigKey = 'f'.repeat(64)
        await window.viewerTest.controller.play(clip)
        clip.rigKey = original
    })
    assert.match((await snapshot(runtime)).error, /rig is incompatible/)
    assert.equal((await snapshot(runtime)).cachedAnimations, 0)
    assert.equal((await snapshot(runtime)).atRest, true)
    passed.push('downloaded valid GLB with incompatible declared rig is rejected before playback')
    const animationPath = await runtime.evaluate(() => window.viewerTest.model.animations[0].path)
    let release, reached
    const blocked = new Promise(resolve => { release = resolve })
    const requested = new Promise(resolve => { reached = resolve })
    await runtime.route(`**/${animationPath}`, async route => { reached(); await blocked; await route.continue().catch(() => {}) })
    await runtime.evaluate(() => { void window.viewerTest.controller.play(window.viewerTest.model.animations[0]) })
    await requested
    await runtime.evaluate(() => window.viewerTest.controller.reset())
    release()
    await runtime.waitForTimeout(250)
    assert.equal((await snapshot(runtime)).playing, false)
    assert.equal((await snapshot(runtime)).cachedAnimations, 0)
    assert.equal((await snapshot(runtime)).atRest, true)
    await runtime.unroute(`**/${animationPath}`)
    passed.push('reset cancels pending animation; late completion cannot play/cache stale clip')

    const modelPath = await runtime.evaluate(() => window.viewerTest.model.path)
    await runtime.goto(server.url)
    let releaseModel, reachedModel
    const blockedModel = new Promise(resolve => { releaseModel = resolve })
    const requestedModel = new Promise(resolve => { reachedModel = resolve })
    await runtime.route(`**/${modelPath}`, async route => { reachedModel(); await blockedModel; await route.continue().catch(() => {}) })
    await runtime.getByRole('button', { name: 'View 3D model' }).click()
    await requestedModel
    await expect(runtime.locator('canvas')).toHaveCount(1)
    await runtime.getByRole('button', { name: 'Close', exact: true }).click()
    releaseModel()
    await runtime.waitForTimeout(250)
    await expect(runtime.locator('canvas')).toHaveCount(0)
    await expect(runtime.locator('dialog')).toHaveCount(0)
    passed.push('closing Vue dialog during model download prevents late canvas/scene restoration')
    await runtimeContext.close()

    const mobileContext = await browser.newContext({ viewport: { width: 320, height: 700 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
    const mobile = await mobileContext.newPage()
    mobile.on('pageerror', error => errors.push(error.message))
    await mobile.goto(server.url)
