    assert.ok(dialog.x >= 0 && dialog.x + dialog.width <= 320.1)
    const close = await mobile.getByRole('button', { name: 'Close', exact: true }).boundingBox()
    assert.ok(close.x >= 0 && close.x + close.width <= 320)
    assert.ok(close.y >= 0 && close.y + close.height <= dialog.y + .1)
    const modelArea = await mobile.locator('.model-host').boundingBox()
    const actionsArea = await mobile.locator('.model-actions').boundingBox()
    near(modelArea.height, actionsArea.height)
    assert.ok(dialog.y + dialog.height - (modelArea.y + modelArea.height) < 8)
    const header = await mobile.locator('.dialog-header').boundingBox()
    assert.ok(header.x >= 0 && header.y >= 0 && header.x + header.width <= 320)
    await mobile.screenshot({ path: path.join(output, 'mobile.png') })
